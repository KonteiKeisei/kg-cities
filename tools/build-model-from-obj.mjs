// Turn a detailed building mesh (OBJ, Z up) into a light tiered model for the map: the mesh is
// sliced every half unit, each slice's outline kept as its convex hull, and runs of slices with
// the same outline merged into one tier (a prism). Setback towers (the Empire State Building)
// keep their profile with a few dozen faces instead of a quarter million.
//   node tools/build-model-from-obj.mjs <mesh.obj> <metres per unit> <out.mjs> <export name>

import { readFile, writeFile } from "node:fs/promises";

const [file, scaleArg, out, name] = process.argv.slice(2);
const SCALE = Number(scaleArg);
const STEP = 0.5, TOL = 0.3;

const txt = await readFile(file, "utf8");
const v = [], tris = [];
for (const line of txt.split("\n")) {
  if (line.startsWith("v ")) v.push(line.slice(2).trim().split(/\s+/).map(Number));
  else if (line.startsWith("f ")) {
    const idx = line.slice(2).trim().split(/\s+/).map((s) => parseInt(s, 10) - 1);
    for (let i = 1; i + 1 < idx.length; i++) tris.push([idx[0], idx[i], idx[i + 1]]);
  }
}
// Triangles by height range, so each slice only looks at the ones it can cross.
const zr = tris.map((t) => [Math.min(...t.map((i) => v[i][2])), Math.max(...t.map((i) => v[i][2]))]);

function section(z) {
  const pts = [];
  tris.forEach((t, ti) => {
    if (zr[ti][0] > z || zr[ti][1] < z) return;
    for (let a = 0; a < 3; a++) {
      const P = v[t[a]], Q = v[t[(a + 1) % 3]];
      if ((P[2] - z) * (Q[2] - z) < 0) {
        const k = (z - P[2]) / (Q[2] - P[2]);
        pts.push([P[0] + k * (Q[0] - P[0]), P[1] + k * (Q[1] - P[1])]);
      }
    }
  });
  return pts;
}

function hull(pts) {
  const p = [...pts].sort((a, b) => a[0] - b[0] || a[1] - b[1]);
  const cross = (o, a, b) => (a[0] - o[0]) * (b[1] - o[1]) - (a[1] - o[1]) * (b[0] - o[0]);
  const half = (list) => { const h = []; for (const q of list) { while (h.length >= 2 && cross(h.at(-2), h.at(-1), q) <= 1e-9) h.pop(); h.push(q); } return h; };
  const lower = half(p), upper = half(p.reverse());
  return [...lower.slice(0, -1), ...upper.slice(0, -1)];
}

/** Drop hull corners that barely turn (a curved outline sampled finely). */
function simplify(ring, minTurn = 0.06, minEdge = 0.15) {
  let r = ring;
  for (let pass = 0; pass < 4; pass++) {
    r = r.filter((p, i) => {
      const a = r[(i - 1 + r.length) % r.length], b = r[(i + 1) % r.length];
      const u = [p[0] - a[0], p[1] - a[1]], w = [b[0] - p[0], b[1] - p[1]];
      const lu = Math.hypot(...u), lw = Math.hypot(...w);
      if (lu < minEdge || lw < minEdge) return r.length <= 4;
      return Math.abs(Math.atan2(u[0] * w[1] - u[1] * w[0], u[0] * w[0] + u[1] * w[1])) > minTurn;
    });
  }
  return r;
}

const bbox = (r) => [Math.min(...r.map((p) => p[0])), Math.min(...r.map((p) => p[1])), Math.max(...r.map((p) => p[0])), Math.max(...r.map((p) => p[1]))];
const same = (a, b) => a.every((x, i) => Math.abs(x - b[i]) <= TOL);

const zmax = Math.max(...v.map((p) => p[2]));
const tiers = [];
for (let z = STEP / 2; z < zmax; z += STEP) {
  const pts = section(z);
  if (pts.length < 3) continue;
  const ring = simplify(hull(pts));
  if (ring.length < 3) continue;
  const box = bbox(ring);
  const last = tiers.at(-1);
  if (last && same(last.box, box) && Math.abs(last.z1 - (z - STEP / 2)) < 1e-6) { last.z1 = z + STEP / 2; continue; }
  tiers.push({ z0: z - STEP / 2, z1: z + STEP / 2, box, ring });
}
tiers.at(-1).z1 = zmax;
// One solid stack: from the ground, each tier starting where the one below ends (a slice that
// found too little to outline leaves no gap).
tiers[0].z0 = 0;
for (let i = 1; i < tiers.length; i++) tiers[i].z0 = tiers[i - 1].z1;

// Centred on the main shaft (the tallest tier at least a quarter of the height's width).
const shaft = tiers.filter((t) => t.z1 - t.z0 > zmax * 0.1).sort((a, b) => (b.z1 - b.z0) - (a.z1 - a.z0))[0] ?? tiers[0];
const cx = (shaft.box[0] + shaft.box[2]) / 2, cy = (shaft.box[1] + shaft.box[3]) / 2;
const m = (x) => +(x * SCALE).toFixed(2);
const data = tiers.map((t) => [m(t.z0), m(t.z1), t.ring.map(([x, y]) => [m(x - cx), m(y - cy)])]);

await writeFile(out, `// Generated by tools/build-model-from-obj.mjs from ${file.split(/[\\/]/).pop()} (${tris.length} triangles):
// ${data.length} tiers, [base m, top m, outline [[u, v] m]], u along the model's x axis, centred on its shaft.
export const ${name} = ${JSON.stringify(data)};
`);
console.log(`${data.length} tiers, top ${m(zmax)} m, shaft ${m(shaft.box[2] - shaft.box[0])} x ${m(shaft.box[3] - shaft.box[1])} m`);
for (const [z0, z1, r] of data) console.log(`${String(z0).padStart(7)} .. ${String(z1).padEnd(7)} ${r.length} corners`);
